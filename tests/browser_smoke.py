"""Run against a local scripted-mode server; creates synthetic demo sessions."""
from pathlib import Path
from playwright.sync_api import sync_playwright

with sync_playwright() as p:
    browser = p.chromium.launch(args=['--use-fake-ui-for-media-stream', '--use-fake-device-for-media-stream'])
    page = browser.new_page(viewport={'width': 1440, 'height': 1100})
    errors = []
    page.on('pageerror', lambda exc: errors.append(str(exc)))
    page.goto('http://127.0.0.1:8000')
    page.get_by_text('Scripted demo · no LLM').wait_for()
    page.screenshot(path='/tmp/northstar-desktop.png', full_page=True)
    page.locator('#audio-enabled').uncheck()
    page.locator('#start').click()
    page.locator('#message').fill('I am Maya Chen, NS-1001. My VPN is broken')
    page.locator('#send').click()
    page.get_by_text('Does it load?', exact=False).wait_for()
    page.locator('#message').fill('yes')
    page.locator('#send').click()
    page.get_by_text('Does the VPN connect now?', exact=False).wait_for()
    page.locator('#message').fill('It works now')
    page.locator('#send').click()
    page.get_by_text('One less thing on your list.').wait_for()
    page.locator('#end').click()
    page.locator('#start').click()
    page.locator('#message').fill('I am Maya Chen, NS-1001. I need restricted software for a customer report')
    page.locator('#send').click()
    page.locator('#messages').get_by_text('No access has been granted.', exact=False).wait_for()
    page.locator('[data-view="review"]').click()
    ticket = page.locator('.ticket').filter(has=page.locator('[data-decision="approved"]')).first
    ticket.locator('input').fill('Demo Reviewer')
    ticket.locator('textarea').fill('Approved for the customer report. IT to provision access.')
    ticket.get_by_text('Approve request', exact=True).click()
    page.locator('.badge').filter(has_text='approved').first.wait_for()
    page.locator('[data-view="history"]').click()
    page.locator('#history').get_by_text('approved pending fulfillment', exact=True).first.wait_for()
    page.locator('[data-view="support"]').click()
    page.locator('.testing summary').click()
    page.locator('#fault').select_option('ticket')
    page.locator('#start').click()
    page.locator('#message').fill('I am Maya Chen NS-1001. I need restricted software for a report')
    page.locator('#send').click()
    page.locator('#retry-ticket').wait_for()
    page.locator('#retry-ticket').click()
    page.locator('#messages').get_by_text('No access has been granted.', exact=False).wait_for()
    page.set_viewport_size({'width':390, 'height':844})
    page.screenshot(path='/tmp/northstar-mobile.png',full_page=True)
    assert page.evaluate('document.documentElement.scrollWidth <= window.innerWidth')
    assert not errors, errors
    # Exercise actual MediaRecorder capture with a fake browser microphone.
    # Only external transcription is mocked; the backend workflow remains real.
    voice = browser.new_page(permissions=['microphone'])
    voice.on('pageerror', lambda exc: errors.append(str(exc)))
    def voice_config(route):
        response = route.fetch()
        payload = response.json()
        payload['voice_ready'] = True
        route.fulfill(json=payload)
    voice.route('**/api/config', voice_config)
    voice.route('**/api/voice/transcribe', lambda route: route.fulfill(json={'text': 'Maya Chen NS-1001. My VPN is broken'}))
    voice.goto('http://127.0.0.1:8000')
    voice.locator('#audio-enabled').uncheck()
    voice.locator('#start').click()
    voice.locator('#record').click()
    voice.get_by_role('button', name='Stop & send').wait_for()
    voice.wait_for_timeout(250)
    voice.locator('#record').click()
    voice.get_by_text('Does it load?', exact=False).wait_for()
    voice.unroute('**/api/voice/transcribe')
    voice.route('**/api/voice/transcribe', lambda route: route.fulfill(status=502, json={'detail': 'Voice quota reached. Continue with text.'}))
    voice.locator('#record').click()
    voice.get_by_role('button', name='Stop & send').wait_for()
    voice.wait_for_timeout(250)
    voice.locator('#record').click()
    voice.get_by_text('Voice quota reached. Continue with text.').wait_for()
    voice.locator('#message').fill('It works now')
    voice.locator('#send').click()
    voice.get_by_text('One less thing on your list.').wait_for()
    assert not errors, errors
    browser.close()
    print('Browser smoke passed: resolution, approval, ticket retry, mobile layout, microphone capture and voice-error text fallback; no JavaScript errors.')
